// ৩. .padStart() এর ম্যাজিক ব্যবহার করে মাস্কিং করা
// আমরা চাচ্ছি মোট দৈর্ঘ্য ১৬ হবে, আর বাম পাশের বাকি ঘরগুলো '*' দিয়ে পূরণ হবে
